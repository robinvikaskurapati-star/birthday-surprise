import React, { useEffect, useState } from 'react';

export default function FloatingHearts() {
  const [clickHearts, setClickHearts] = useState([]);

  // Generate static drifting background particles
  const particles = [
    { id: 1, icon: '💖', left: '8%', delay: '0s', duration: '14s', size: 'text-xl' },
    { id: 2, icon: '✨', left: '18%', delay: '3s', duration: '16s', size: 'text-sm' },
    { id: 3, icon: '🌸', left: '28%', delay: '1s', duration: '18s', size: 'text-lg' },
    { id: 4, icon: '💗', left: '42%', delay: '4s', duration: '15s', size: 'text-2xl' },
    { id: 5, icon: '⭐', left: '55%', delay: '2s', duration: '13s', size: 'text-sm' },
    { id: 6, icon: '🎀', left: '68%', delay: '5s', duration: '17s', size: 'text-xl' },
    { id: 7, icon: '💕', left: '82%', delay: '0.5s', duration: '16s', size: 'text-lg' },
    { id: 8, icon: '🌷', left: '92%', delay: '3.5s', duration: '19s', size: 'text-base' },
  ];

  // Spawn a floating heart on click/tap anywhere
  useEffect(() => {
    const handleClick = (e) => {
      // Don't spawn if clicked on buttons or inputs
      if (['BUTTON', 'INPUT', 'TEXTAREA', 'A'].includes(e.target.tagName)) return;

      const icons = ['💗', '💖', '✨', '🌸', '💕'];
      const randomIcon = icons[Math.floor(Math.random() * icons.length)];
      const newHeart = {
        id: Date.now() + Math.random(),
        x: e.clientX,
        y: e.clientY,
        icon: randomIcon,
      };

      setClickHearts((prev) => [...prev.slice(-15), newHeart]);

      setTimeout(() => {
        setClickHearts((prev) => prev.filter((h) => h.id !== newHeart.id));
      }, 1200);
    };

    window.addEventListener('click', handleClick);
    return () => window.removeEventListener('click', handleClick);
  }, []);

  return (
    <div className="fixed inset-0 pointer-events-none z-10 overflow-hidden">
      {/* Drifting background floating elements */}
      {particles.map((p) => (
        <div
          key={p.id}
          className={`absolute bottom-[-50px] ${p.size} opacity-40 select-none`}
          style={{
            left: p.left,
            animation: `driftUp ${p.duration} linear infinite`,
            animationDelay: p.delay,
          }}
        >
          {p.icon}
        </div>
      ))}

      {/* Burst hearts generated by user taps/clicks */}
      {clickHearts.map((h) => (
        <div
          key={h.id}
          className="fixed text-2xl select-none z-50 pointer-events-none"
          style={{
            left: `${h.x}px`,
            top: `${h.y}px`,
            animation: 'popAndFade 1.2s forwards ease-out',
            transform: 'translate(-50%, -50%)',
          }}
        >
          {h.icon}
        </div>
      ))}

      <style>{`
        @keyframes driftUp {
          0% {
            transform: translateY(0) rotate(0deg);
            opacity: 0;
          }
          20% {
            opacity: 0.5;
          }
          80% {
            opacity: 0.5;
          }
          100% {
            transform: translateY(-110vh) rotate(360deg);
            opacity: 0;
          }
        }
        @keyframes popAndFade {
          0% {
            transform: translate(-50%, -50%) scale(0.4);
            opacity: 1;
          }
          50% {
            transform: translate(-50%, -100%) scale(1.3);
            opacity: 0.9;
          }
          100% {
            transform: translate(-50%, -160%) scale(0.8);
            opacity: 0;
          }
        }
      `}</style>
    </div>
  );
}
